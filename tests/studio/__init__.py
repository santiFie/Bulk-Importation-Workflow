# Directorio de scripts para testeo manual de nodos en LangGraph Studio.
#
# Los archivos de este directorio NO son tests de pytest. Son scripts
# ejecutables directamente con `python` para invocar nodos del grafo
# de forma aislada y observar el resultado en LangSmith.
#
# Cuándo usarlos:
#   - Al hacer cambios en un nodo y querer verificarlo rápidamente
#     sin correr el pipeline completo.
#   - Para debugging interactivo desde LangGraph Studio.
#   - Para reproducir un comportamiento específico con datos reales.
